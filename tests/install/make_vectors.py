#!/usr/bin/env python3
"""Writes tests/install/vectors.hpp: known answers for source/install/'s
crypto, from an implementation of its own (pyca/cryptography), so the suite
does not check the code against itself. Deterministic but for the RSA key,
made once: run it again only to change the vectors.

Usage: python3 tests/install/make_vectors.py > tests/install/vectors.hpp
"""
import hashlib

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def stream(n, seed):
    """n bytes of a fixed pseudo-random stream."""
    out = b""
    i = 0
    while len(out) < n:
        out += hashlib.sha256(seed + i.to_bytes(4, "big")).digest()
        i += 1
    return out[:n]


def hexarr(name, b):
    body = ", ".join(f"0x{x:02x}" for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{{body}}};"


def enc(cipher, data):
    e = cipher.encryptor()
    return e.update(data) + e.finalize()


lines = ["// Generated by tests/install/make_vectors.py: do not edit.", "#pragma once", "#include <cstdint>", ""]

# XTS, Nintendo's tweak: sector numbers big-endian. Three sectors from 1.
xts_key = stream(32, b"xts key")
xts_plain = stream(3 * 0x200, b"xts plain")
xts_cipher = b"".join(enc(Cipher(algorithms.AES(xts_key), modes.XTS((1 + s).to_bytes(16, "big"))),
                          xts_plain[s * 0x200:(s + 1) * 0x200]) for s in range(3))
lines += [hexarr("XTS_KEY", xts_key), f'static const char XTS_PLAIN_SEED[] = "xts plain";',
          f'static const char XTS_CIPHER_SHA256[] = "{hashlib.sha256(xts_cipher).hexdigest()}";', ""]

# CTR: a stream from an IV whose low half is about to carry.
ctr_key = stream(16, b"ctr key")
ctr_iv = bytes.fromhex("0011223344556677fffffffffffffffe")
ctr_plain = stream(0x300, b"ctr plain")
ctr_cipher = enc(Cipher(algorithms.AES(ctr_key), modes.CTR(ctr_iv)), ctr_plain)
lines += [hexarr("CTR_KEY", ctr_key), hexarr("CTR_IV", ctr_iv), 'static const char CTR_PLAIN_SEED[] = "ctr plain";',
          f'static const char CTR_CIPHER_SHA256[] = "{hashlib.sha256(ctr_cipher).hexdigest()}";', ""]

# ECB, two blocks.
ecb_key = stream(16, b"ecb key")
ecb_plain = stream(32, b"ecb plain")
lines += [hexarr("ECB_KEY", ecb_key), hexarr("ECB_PLAIN", ecb_plain),
          hexarr("ECB_CIPHER", enc(Cipher(algorithms.AES(ecb_key), modes.ECB()), ecb_plain)), ""]

# RSA-2048-PSS, SHA-256, MGF1-SHA256, a 32-byte salt, over 0x200 bytes.
key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
modulus = key.public_key().public_numbers().n.to_bytes(256, "big")
msg = stream(0x200, b"rsa message")
sig = key.sign(msg, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())
lines += [hexarr("RSA_MODULUS", modulus), 'static const char RSA_MESSAGE_SEED[] = "rsa message";', hexarr("RSA_SIGNATURE", sig)]
print("\n".join(lines))
