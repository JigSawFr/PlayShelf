#!/usr/bin/env python3
"""Writes tests/library/vectors.hpp: a self-signed certificate (an EC P-256
key and an RSA-2048 one, with and without the version field's default) and
the SHA-256 of its SubjectPublicKeyInfo as pyca/cryptography computes it, so
source/library/server.cpp's DER reading is checked against another
implementation. Run it again only to change the vectors.

Usage: python3 tests/library/make_vectors.py > tests/library/vectors.hpp
"""
import base64
import datetime
import hashlib

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.x509.oid import NameOID


def cert(key, cn):
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
    t = datetime.datetime(2026, 1, 1, tzinfo=datetime.timezone.utc)
    return (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(0x1234567890).not_valid_before(t).not_valid_after(t + datetime.timedelta(days=3650))
            .add_extension(x509.SubjectAlternativeName([x509.DNSName("library.lan")]), critical=False)
            .sign(key, hashes.SHA256()))


def arr(name, b):
    return f"static const uint8_t {name}[{len(b)}] = {{{', '.join(f'0x{x:02x}' for x in b)}}};"


out = ["// Generated by tests/library/make_vectors.py: do not edit.", "#pragma once", "#include <cstdint>", ""]
for label, key in (("EC", ec.generate_private_key(ec.SECP256R1())), ("RSA", rsa.generate_private_key(65537, 2048))):
    c = cert(key, f"PlayShelf test {label}")
    der = c.public_bytes(serialization.Encoding.DER)
    spki = key.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    out += [arr(f"CERT_{label}", der),
            f'static const char CERT_{label}_PEM[] = R"({c.public_bytes(serialization.Encoding.PEM).decode()})";',
            f'static const char CERT_{label}_PIN[] = "sha256//{base64.b64encode(hashlib.sha256(spki).digest()).decode()}";', ""]
print("\n".join(out))
